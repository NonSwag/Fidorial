import java.io.IOException;
import java.io.InputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.MessageDigest;
import java.util.HexFormat;

/**
 * Helpers shared by the build scripts. Plain JDK only, so that every script can use them.
 *
 * <p>Line format shared by the server's {@code libraries.list} and every plugin's lock file:
 * {@code group:artifact:version[:classifier] <sha256> <size>}.
 */
final class LibraryLists {

    private LibraryLists() {
    }

    static String header(final String what, final String script) {
        return "# " + what + "\n# Generated by scripts/" + script + " — do not edit.\n";
    }

    static String sha256(final Path file) throws IOException {
        try (InputStream in = Files.newInputStream(file)) {
            final MessageDigest digest = MessageDigest.getInstance("SHA-256");
            final byte[] buffer = new byte[64 * 1024];
            for (int read; (read = in.read(buffer)) >= 0; ) {
                digest.update(buffer, 0, read);
            }
            return HexFormat.of().formatHex(digest.digest());
        } catch (final java.security.NoSuchAlgorithmException e) {
            throw new IllegalStateException(e);
        }
    }
}
