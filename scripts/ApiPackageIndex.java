import com.google.gson.JsonObject;

import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.SortedSet;
import java.util.TreeSet;
import java.util.stream.Stream;
import java.util.zip.ZipEntry;
import java.util.zip.ZipFile;

/**
 * Prebuild hook of fidorial-server: lists every package reachable from fidorial-api and its runtime
 * dependencies into {@code src/main/resources/META-INF/fidorial/api-packages.list} (git-ignored).
 *
 * <p>At runtime the plugin class loader treats these packages as parent-first: a plugin that bundles
 * its own Adventure or Gson still gets the server's copy, so a {@code Component} crossing the API boundary
 * is never a {@code ClassCastException}. Everything outside this list is child-first, which is what lets
 * two plugins ship conflicting versions of the same library.
 */
public final class ApiPackageIndex {

    public static void main(final String[] args) throws Exception {
        final JsonObject info = JpmInfo.read();
        final JsonObject api = JpmInfo.module(info, "fidorial-api");
        final SortedSet<String> packages = new TreeSet<>();

        // fidorial-api's own packages, read from its sources so the index does not need it built first
        // (javac writes one class, at least package-info, for every package with a source file)
        final Path sources = Path.of(api.get("sourceDir").getAsString());
        try (Stream<Path> walk = Files.walk(sources)) {
            walk.filter(f -> f.toString().endsWith(".java") && !f.getFileName().toString().equals("module-info.java"))
                    .map(f -> sources.relativize(f.getParent()).toString().replace(java.io.File.separatorChar, '.'))
                    .filter(p -> !p.isEmpty())
                    .forEach(packages::add);
        }

        for (final Path jar : JpmInfo.dependencyJars(api, List.of("compile", "runtime"))) {
            try (ZipFile zip = new ZipFile(jar.toFile())) {
                zip.stream()
                        .filter(e -> !e.isDirectory() && e.getName().endsWith(".class"))
                        .map(ZipEntry::getName)
                        .filter(n -> n.lastIndexOf('/') > 0)
                        .map(n -> n.substring(0, n.lastIndexOf('/')).replace('/', '.'))
                        .forEach(packages::add);
            }
        }
        // multi-release jars (META-INF.versions.N...) and other metadata are not packages
        packages.removeIf(p -> p.startsWith("META-INF"));

        final Path module = Path.of(System.getenv("JPM_MODULE_DIR"));
        final Path out = module.resolve("src/main/resources/META-INF/fidorial/api-packages.list");
        final String text = "# Packages owned by the server: always loaded parent-first for plugins.\n"
                + "# Generated by scripts/ApiPackageIndex.java — do not edit.\n"
                + String.join("\n", packages) + "\n";
        Files.createDirectories(out.getParent());
        if (!Files.exists(out) || !Files.readString(out).equals(text)) {
            Files.writeString(out, text);
        }
        System.out.println("    API package index: " + packages.size() + " packages");
    }

    private ApiPackageIndex() {
    }
}
